const {chromium}=require(process.env.FURBOMEK_PLAYWRIGHT || 'playwright');
const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
const root=pathToFileURL(path.resolve(__dirname,'..')+path.sep).href;
const output=process.env.FURBOMEK_AVATAR_QA_OUTPUT;
let browser;
(async()=>{
 browser=await chromium.launch({headless:true,executablePath:process.env.FURBOMEK_CHROMIUM,args:['--disable-gpu','--disable-background-networking']});
 const page=await browser.newPage({viewport:{width:1280,height:720}}); const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(root+'index.html'); await page.waitForFunction(()=>window.FurbomekAvatar?.snapshot().visible);
 assert.equal(await page.locator('#caption').textContent(),'Activity unavailable');
 if(output) await page.screenshot({path:path.join(output,'offline.png'),omitBackground:true});
 await page.goto(root+'fixture.html'); await page.waitForFunction(()=>window.FurbomekAvatar?.snapshot().status==='thinking');
 assert.equal(await page.locator('#mode').textContent(),'FIXTURE · NOT LIVE');
 if(output) await page.screenshot({path:path.join(output,'fixture.png'),omitBackground:true});
 await page.waitForFunction(()=>window.FurbomekAvatar?.snapshot().status==='interrupted');
 await page.waitForFunction(()=>document.querySelector('#caption').textContent==='Activity unavailable');
 assert.equal(await page.locator('#caption').textContent(),'Activity unavailable');
 await page.goto(root+'index.html');
 await page.waitForFunction(()=>window.FurbomekAvatar?.snapshot().visible);
 await page.evaluate(()=>window.FurbomekAvatar.apply_event(JSON.stringify({schemaVersion:'furbomek.character.v1',kind:'agent.activity',source:'hermes-adapter',audience:'public',sensitivity:'public',seq:1,observedAt:new Date().toISOString(),ttlMs:2000,payload:{title:'Furb-o-Mek',summary:'<img src=x onerror=alert(1)>',status:'idle',tool:'AGENT'}})));
 assert.equal(await page.locator('#caption img').count(),0);
 assert.equal(await page.locator('#caption').textContent(),'<img src=x onerror=alert(1)>');
 assert.deepEqual(errors,[]);
 console.log('PASS browser: offline asset, labelled fixture, interrupted and expiry, literal HTML text, no page errors.');
 })().catch(e=>{console.error(e);process.exitCode=1}).finally(async()=>{if(browser) await browser.close();});
